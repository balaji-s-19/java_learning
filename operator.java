public class operator {
    public static void main(String[] args) {
        int a=1;
        int b=2;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a==b);
        System.out.println(a>b);
        //ternary operaters
        System.out.println(a>b ? "a is greater then b" : "b is greater then a");

    }
    
}
